-- RPT v1 — oracle19c — copy-and-run against a clean schema
-- BLOCK 1 SEQUENCES: none — every PK uses the identity clause

-- BLOCK 2 PARENT TABLES
CREATE TABLE RPT_CHECK_RUN (
    CHECK_RUN_ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    SERVICE_CODE VARCHAR2(100 CHAR) NOT NULL,
    VERSION_NUMBER NUMBER(10) NOT NULL,
    FETCH_MODE VARCHAR2(10 CHAR) NOT NULL,
    REQUEST_NUMBER VARCHAR2(100 CHAR) NOT NULL,
    EMPLOYEE_ID VARCHAR2(100 CHAR) NOT NULL,
    CHECK_STATUS VARCHAR2(30 CHAR) NOT NULL,
    STARTED_AT TIMESTAMP WITH TIME ZONE NOT NULL,
    RUNNING_SINCE TIMESTAMP WITH TIME ZONE,
    ENDED_AT TIMESTAMP WITH TIME ZONE,
    OVERALL_STATUS VARCHAR2(30 CHAR),
    COMPARISON_MODEL VARCHAR2(200 CHAR),
    FAILURE_REASON VARCHAR2(30 CHAR),
    FAILURE_DETAIL CLOB,
    EMPLOYEE_DECISION VARCHAR2(30 CHAR),
    DECIDED_BY VARCHAR2(100 CHAR),
    DECIDED_AT TIMESTAMP WITH TIME ZONE,
    APPROVAL_API_EXECUTED NUMBER(1),
    CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);

-- BLOCK 3 CHILD TABLES (intra-module FK target RPT_CHECK_RUN already created)
CREATE TABLE RPT_FINDING (
    FINDING_ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    POSITION NUMBER(10) NOT NULL,
    CONDITION_TEXT CLOB NOT NULL,
    FINDING_OUTCOME VARCHAR2(30 CHAR) NOT NULL,
    EVIDENCE CLOB NOT NULL,
    NOTE CLOB NOT NULL,
    CHECK_RUN_ID NUMBER(19) NOT NULL,
    CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE RPT_CHECK_DOCUMENT (
    CHECK_DOCUMENT_ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    POSITION NUMBER(10) NOT NULL,
    DOCUMENT_TYPE VARCHAR2(100 CHAR) NOT NULL,
    SOURCE_MODE VARCHAR2(10 CHAR) NOT NULL,
    READ_STATUS VARCHAR2(30 CHAR) NOT NULL,
    UNREADABLE_REASON VARCHAR2(30 CHAR),
    DETAIL CLOB,
    CHECK_RUN_ID NUMBER(19) NOT NULL,
    CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE RPT_UNREAD_QUERY (
    UNREAD_QUERY_ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    POSITION NUMBER(10) NOT NULL,
    QUERY_NAME VARCHAR2(100 CHAR) NOT NULL,
    DETAIL CLOB NOT NULL,
    CHECK_RUN_ID NUMBER(19) NOT NULL,
    CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);

