-- BLOCK 5a PRIMARY KEYS
ALTER TABLE RPT_CHECK_RUN ADD CONSTRAINT PK_RPT_CHECK_RUN PRIMARY KEY (CHECK_RUN_ID);
ALTER TABLE RPT_FINDING ADD CONSTRAINT PK_RPT_FINDING PRIMARY KEY (FINDING_ID);
ALTER TABLE RPT_CHECK_DOCUMENT ADD CONSTRAINT PK_RPT_CHECK_DOCUMENT PRIMARY KEY (CHECK_DOCUMENT_ID);
ALTER TABLE RPT_UNREAD_QUERY ADD CONSTRAINT PK_RPT_UNREAD_QUERY PRIMARY KEY (UNREAD_QUERY_ID);

-- BLOCK 5b UNIQUE (one position per report part — REQ-RPT-010; the leading CHECK_RUN_ID also indexes each FK)
ALTER TABLE RPT_FINDING ADD CONSTRAINT UQ_RPT_FINDING_RUN_POS UNIQUE (CHECK_RUN_ID, POSITION);
ALTER TABLE RPT_CHECK_DOCUMENT ADD CONSTRAINT UQ_RPT_CHECK_DOCUMENT_RUN_POS UNIQUE (CHECK_RUN_ID, POSITION);
ALTER TABLE RPT_UNREAD_QUERY ADD CONSTRAINT UQ_RPT_UNREAD_QUERY_RUN_POS UNIQUE (CHECK_RUN_ID, POSITION);

-- BLOCK 5c CHECK
-- closed lists handed to RPT by CHK (CON-CHK-001 … CON-CHK-003; ADR-CHK-016) and DOC (CON-DOC-001, CON-DOC-002; ADR-DOC-010) — RULE-RPT-006
ALTER TABLE RPT_CHECK_RUN ADD CONSTRAINT CHK_RPT_CHECK_RUN_CHECK_STATUS CHECK (CHECK_STATUS IN ('AWAITING_DOCUMENTS', 'RUNNING', 'COMPLETED', 'FAILED'));
ALTER TABLE RPT_CHECK_RUN ADD CONSTRAINT CHK_RPT_CHECK_RUN_FETCH_MODE CHECK (FETCH_MODE IN ('path', 'blob', 'manual'));
ALTER TABLE RPT_CHECK_RUN ADD CONSTRAINT CHK_RPT_CHECK_RUN_OVERALL_STATUS CHECK (OVERALL_STATUS IS NULL OR OVERALL_STATUS IN ('COMPLIANT', 'NOT_COMPLIANT', 'NEEDS_MANUAL_REVIEW'));
ALTER TABLE RPT_CHECK_RUN ADD CONSTRAINT CHK_RPT_CHECK_RUN_FAILURE_REASON CHECK (FAILURE_REASON IS NULL OR FAILURE_REASON IN ('TIMED_OUT', 'MODEL_UNAVAILABLE', 'MODEL_OUTPUT_INVALID', 'MODEL_NOT_PERMITTED', 'UPLOAD_WINDOW_EXPIRED', 'INTERRUPTED', 'INTERNAL_ERROR'));
ALTER TABLE RPT_FINDING ADD CONSTRAINT CHK_RPT_FINDING_FINDING_OUTCOME CHECK (FINDING_OUTCOME IN ('SATISFIED', 'NOT_SATISFIED', 'UNDETERMINED'));
ALTER TABLE RPT_CHECK_DOCUMENT ADD CONSTRAINT CHK_RPT_CHECK_DOCUMENT_SOURCE_MODE CHECK (SOURCE_MODE IN ('path', 'blob', 'manual'));
ALTER TABLE RPT_CHECK_DOCUMENT ADD CONSTRAINT CHK_RPT_CHECK_DOCUMENT_READ_STATUS CHECK (READ_STATUS IN ('READ', 'MISSING', 'UNREADABLE'));
ALTER TABLE RPT_CHECK_DOCUMENT ADD CONSTRAINT CHK_RPT_CHECK_DOCUMENT_UNREADABLE_REASON CHECK (UNREADABLE_REASON IS NULL OR UNREADABLE_REASON IN ('OUTSIDE_STORAGE_ROOT', 'NOT_FOUND', 'TOO_LARGE', 'UNSUPPORTED_FORMAT', 'READING_FAILED', 'OUT_OF_TIME', 'SOURCE_QUERY_FAILED', 'MODEL_NOT_PERMITTED'));
-- RPT's own closed list EMPLOYEE_DECISION (CON-RPT-002) — RULE-RPT-013
ALTER TABLE RPT_CHECK_RUN ADD CONSTRAINT CHK_RPT_CHECK_RUN_EMPLOYEE_DECISION CHECK (EMPLOYEE_DECISION IS NULL OR EMPLOYEE_DECISION IN ('APPROVED', 'REJECTED'));
ALTER TABLE RPT_CHECK_RUN ADD CONSTRAINT CHK_RPT_CHECK_RUN_APPROVAL_API_EXECUTED CHECK (APPROVAL_API_EXECUTED IS NULL OR APPROVAL_API_EXECUTED IN (0, 1));
-- shape of a Check run by status — REQ-RPT-008, REQ-RPT-018, RULE-RPT-003, RULE-RPT-004, RULE-RPT-010
ALTER TABLE RPT_CHECK_RUN ADD CONSTRAINT CHK_RPT_CHECK_RUN_RESULT CHECK (
    (CHECK_STATUS IN ('AWAITING_DOCUMENTS', 'RUNNING') AND OVERALL_STATUS IS NULL AND COMPARISON_MODEL IS NULL AND FAILURE_REASON IS NULL AND ENDED_AT IS NULL)
 OR (CHECK_STATUS = 'COMPLETED' AND OVERALL_STATUS IS NOT NULL AND COMPARISON_MODEL IS NOT NULL AND FAILURE_REASON IS NULL AND ENDED_AT IS NOT NULL)
 OR (CHECK_STATUS = 'FAILED' AND OVERALL_STATUS IS NULL AND COMPARISON_MODEL IS NULL AND FAILURE_REASON IS NOT NULL AND ENDED_AT IS NOT NULL));
ALTER TABLE RPT_CHECK_RUN ADD CONSTRAINT CHK_RPT_CHECK_RUN_ENDED_AT CHECK (ENDED_AT IS NULL OR ENDED_AT >= STARTED_AT);
-- a Check AWAITING_DOCUMENTS is always a manual Check — RULE-RPT-002
ALTER TABLE RPT_CHECK_RUN ADD CONSTRAINT CHK_RPT_CHECK_RUN_AWAITING CHECK (CHECK_STATUS <> 'AWAITING_DOCUMENTS' OR FETCH_MODE = 'manual');
-- the decision is all-or-nothing, only on a COMPLETED Check, and never REJECTED through the Approval API — RULE-RPT-012, RULE-RPT-013, RULE-RPT-014
ALTER TABLE RPT_CHECK_RUN ADD CONSTRAINT CHK_RPT_CHECK_RUN_DECISION CHECK (
    (EMPLOYEE_DECISION IS NULL AND DECIDED_BY IS NULL AND DECIDED_AT IS NULL AND APPROVAL_API_EXECUTED IS NULL)
 OR (EMPLOYEE_DECISION IS NOT NULL AND DECIDED_BY IS NOT NULL AND DECIDED_AT IS NOT NULL AND APPROVAL_API_EXECUTED IS NOT NULL
     AND CHECK_STATUS = 'COMPLETED' AND NOT (EMPLOYEE_DECISION = 'REJECTED' AND APPROVAL_API_EXECUTED = 1)));
-- reason exactly on UNREADABLE — RULE-RPT-008
ALTER TABLE RPT_CHECK_DOCUMENT ADD CONSTRAINT CHK_RPT_CHECK_DOCUMENT_REASON CHECK (
    (READ_STATUS = 'UNREADABLE' AND UNREADABLE_REASON IS NOT NULL) OR (READ_STATUS IN ('READ', 'MISSING') AND UNREADABLE_REASON IS NULL));
ALTER TABLE RPT_FINDING ADD CONSTRAINT CHK_RPT_FINDING_POSITION CHECK (POSITION >= 1);
ALTER TABLE RPT_CHECK_DOCUMENT ADD CONSTRAINT CHK_RPT_CHECK_DOCUMENT_POSITION CHECK (POSITION >= 1);
ALTER TABLE RPT_UNREAD_QUERY ADD CONSTRAINT CHK_RPT_UNREAD_QUERY_POSITION CHECK (POSITION >= 1);
ALTER TABLE RPT_CHECK_RUN ADD CONSTRAINT CHK_RPT_CHECK_RUN_VERSION_NUMBER CHECK (VERSION_NUMBER >= 1);

-- BLOCK 5d INTRA-MODULE FOREIGN KEYS (parent PK first; the purge deletes a Check run with its records — REQ-RPT-043, ADR-RPT-011)
ALTER TABLE RPT_FINDING ADD CONSTRAINT FK_RPT_FINDING_RPT_CHECK_RUN FOREIGN KEY (CHECK_RUN_ID) REFERENCES RPT_CHECK_RUN (CHECK_RUN_ID) ON DELETE CASCADE;
ALTER TABLE RPT_CHECK_DOCUMENT ADD CONSTRAINT FK_RPT_CHECK_DOCUMENT_RPT_CHECK_RUN FOREIGN KEY (CHECK_RUN_ID) REFERENCES RPT_CHECK_RUN (CHECK_RUN_ID) ON DELETE CASCADE;
ALTER TABLE RPT_UNREAD_QUERY ADD CONSTRAINT FK_RPT_UNREAD_QUERY_RPT_CHECK_RUN FOREIGN KEY (CHECK_RUN_ID) REFERENCES RPT_CHECK_RUN (CHECK_RUN_ID) ON DELETE CASCADE;

