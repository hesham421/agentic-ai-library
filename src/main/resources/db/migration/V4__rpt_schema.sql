CREATE INDEX IDX_RPT_CHECK_RUN_CHECK_STATUS ON RPT_CHECK_RUN (CHECK_STATUS);  -- REQ-RPT-022
CREATE INDEX IDX_RPT_CHECK_RUN_ENDED_AT ON RPT_CHECK_RUN (ENDED_AT);  -- REQ-RPT-043

