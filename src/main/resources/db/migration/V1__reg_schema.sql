ALTER TABLE REG_SVC_PKG_VER ADD CONSTRAINT PK_REG_SVC_PKG_VER PRIMARY KEY (SERVICE_PACKAGE_VERSION_ID);
ALTER TABLE REG_SVC_QUERY ADD CONSTRAINT PK_REG_SVC_QUERY PRIMARY KEY (SERVICE_QUERY_ID);
ALTER TABLE REG_REQ_DOC ADD CONSTRAINT PK_REG_REQ_DOC PRIMARY KEY (REQUIRED_DOCUMENT_ID);
ALTER TABLE REG_CONNECTION ADD CONSTRAINT PK_REG_CONNECTION PRIMARY KEY (CONNECTION_ID);
ALTER TABLE REG_LOAD_RESULT ADD CONSTRAINT PK_REG_LOAD_RESULT PRIMARY KEY (LOAD_RESULT_ID);

-- BLOCK 5b UNIQUE
ALTER TABLE REG_SVC_PKG ADD CONSTRAINT UQ_REG_SVC_PKG_SERVICE_CODE UNIQUE (SERVICE_CODE);                         -- REQ-REG-001, RULE-REG-002 (canonical lower-case codes, so case variants collide — ADR-REG-017)
ALTER TABLE REG_SVC_PKG_VER ADD CONSTRAINT UQ_REG_SVC_PKG_VER_PKG_VERSION UNIQUE (SERVICE_PACKAGE_ID, VERSION_NUMBER); -- RULE-REG-003
ALTER TABLE REG_SVC_QUERY ADD CONSTRAINT UQ_REG_SVC_QUERY_VER_NAME UNIQUE (SERVICE_PACKAGE_VERSION_ID, QUERY_NAME);  -- RULE-REG-019
ALTER TABLE REG_REQ_DOC ADD CONSTRAINT UQ_REG_REQ_DOC_VER_TYPE UNIQUE (SERVICE_PACKAGE_VERSION_ID, DOCUMENT_TYPE);   -- REQ-REG-037; backstop of RULE-REG-021 (REQ-REG-063), which rejects the package first
ALTER TABLE REG_CONNECTION ADD CONSTRAINT UQ_REG_CONNECTION_CONNECTION_NAME UNIQUE (CONNECTION_NAME);              -- RULE-REG-013

-- BLOCK 5c CHECK
ALTER TABLE REG_SVC_PKG ADD CONSTRAINT CHK_REG_SVC_PKG_AVAILABLE CHECK (AVAILABLE IN (0, 1));
ALTER TABLE REG_SVC_PKG ADD CONSTRAINT CHK_REG_SVC_PKG_SERVICE_CODE CHECK (REGEXP_LIKE(SERVICE_CODE, '^[a-z0-9]+(-[a-z0-9]+)*$'));  -- RULE-REG-022, REQ-REG-064 (ADR-REG-017)
ALTER TABLE REG_SVC_PKG_VER ADD CONSTRAINT CHK_REG_SVC_PKG_VER_FETCH_MODE CHECK (FETCH_MODE IN ('path', 'blob', 'manual'));  -- RULE-REG-008
ALTER TABLE REG_SVC_PKG_VER ADD CONSTRAINT CHK_REG_SVC_PKG_VER_VERSION_NUMBER CHECK (VERSION_NUMBER >= 1);
ALTER TABLE REG_SVC_PKG_VER ADD CONSTRAINT CHK_REG_SVC_PKG_VER_APPROVAL_ENABLED CHECK (APPROVAL_ENABLED IN (0, 1));
ALTER TABLE REG_SVC_PKG_VER ADD CONSTRAINT CHK_REG_SVC_PKG_VER_APPROVAL_API CHECK (APPROVAL_ENABLED = 0 OR APPROVAL_API IS NOT NULL);  -- RULE-REG-011
ALTER TABLE REG_SVC_PKG_VER ADD CONSTRAINT CHK_REG_SVC_PKG_VER_DOC_SOURCE CHECK (FETCH_MODE = 'manual' OR (DOCUMENT_SOURCE_QUERY_NAME IS NOT NULL AND DOCUMENT_TYPE_COLUMN IS NOT NULL));  -- RULE-REG-009
ALTER TABLE REG_SVC_PKG_VER ADD CONSTRAINT CHK_REG_SVC_PKG_VER_PATH_COLUMN CHECK (FETCH_MODE <> 'path' OR DOCUMENT_PATH_COLUMN IS NOT NULL);  -- RULE-REG-009
ALTER TABLE REG_SVC_PKG_VER ADD CONSTRAINT CHK_REG_SVC_PKG_VER_CONTENT_COLUMN CHECK (FETCH_MODE <> 'blob' OR DOCUMENT_CONTENT_COLUMN IS NOT NULL);  -- RULE-REG-009
ALTER TABLE REG_CONNECTION ADD CONSTRAINT CHK_REG_CONNECTION_CONNECTION_TYPE CHECK (CONNECTION_TYPE IN ('mcp', 'jdbc'));  -- RULE-REG-014
ALTER TABLE REG_CONNECTION ADD CONSTRAINT CHK_REG_CONNECTION_READ_ONLY CHECK (READ_ONLY = 1);  -- RULE-REG-015
ALTER TABLE REG_CONNECTION ADD CONSTRAINT CHK_REG_CONNECTION_LIMITED_TO_VIEWS CHECK (LIMITED_TO_VIEWS IN (0, 1));
ALTER TABLE REG_CONNECTION ADD CONSTRAINT CHK_REG_CONNECTION_QUERY_TOOL CHECK (CONNECTION_TYPE <> 'mcp' OR QUERY_TOOL IS NOT NULL);
ALTER TABLE REG_LOAD_RESULT ADD CONSTRAINT CHK_REG_LOAD_RESULT_SUBJECT_KIND CHECK (SUBJECT_KIND IN ('SERVICE_PACKAGE', 'CONNECTION', 'PACKAGE_DIRECTORY'));  -- PACKAGE_DIRECTORY: RULE-REG-023 (ADR-REG-018)
ALTER TABLE REG_LOAD_RESULT ADD CONSTRAINT CHK_REG_LOAD_RESULT_OUTCOME CHECK (OUTCOME IN ('REGISTERED', 'UNCHANGED', 'REJECTED', 'WITHDRAWN', 'ACTIVATED', 'UPDATED', 'REMOVED'));
ALTER TABLE REG_LOAD_RESULT ADD CONSTRAINT CHK_REG_LOAD_RESULT_REASON CHECK (OUTCOME <> 'REJECTED' OR REASON IS NOT NULL);

-- BLOCK 5d INTRA-MODULE FOREIGN KEYS
ALTER TABLE REG_SVC_PKG_VER ADD CONSTRAINT FK_REG_SVC_PKG_VER_REG_SVC_PKG FOREIGN KEY (SERVICE_PACKAGE_ID) REFERENCES REG_SVC_PKG (SERVICE_PACKAGE_ID);
ALTER TABLE REG_SVC_QUERY ADD CONSTRAINT FK_REG_SVC_QUERY_REG_SVC_PKG_VER FOREIGN KEY (SERVICE_PACKAGE_VERSION_ID) REFERENCES REG_SVC_PKG_VER (SERVICE_PACKAGE_VERSION_ID);
ALTER TABLE REG_REQ_DOC ADD CONSTRAINT FK_REG_REQ_DOC_REG_SVC_PKG_VER FOREIGN KEY (SERVICE_PACKAGE_VERSION_ID) REFERENCES REG_SVC_PKG_VER (SERVICE_PACKAGE_VERSION_ID);

