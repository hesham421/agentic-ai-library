-- REG v1 — oracle19c — copy-and-run against a clean schema
-- BLOCK 1 SEQUENCES: none — every PK uses the identity clause

-- BLOCK 2 PARENT TABLES
CREATE TABLE REG_SVC_PKG (
    SERVICE_PACKAGE_ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    SERVICE_CODE VARCHAR2(100 CHAR) NOT NULL,
    AVAILABLE NUMBER(1) DEFAULT 1 NOT NULL,
    REGISTERED_AT TIMESTAMP WITH TIME ZONE NOT NULL,
    WITHDRAWN_AT TIMESTAMP WITH TIME ZONE
);

CREATE TABLE REG_CONNECTION (
    CONNECTION_ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    CONNECTION_NAME VARCHAR2(100 CHAR) NOT NULL,
    CONNECTION_TYPE VARCHAR2(10 CHAR) NOT NULL,
    ENDPOINT VARCHAR2(500 CHAR) NOT NULL,
    QUERY_TOOL VARCHAR2(100 CHAR),
    DIALECT VARCHAR2(30 CHAR) NOT NULL,
    CREDENTIAL_REFERENCE VARCHAR2(200 CHAR) NOT NULL,
    READ_ONLY NUMBER(1) NOT NULL,
    LIMITED_TO_VIEWS NUMBER(1) DEFAULT 0 NOT NULL,
    ENVIRONMENT_NAME VARCHAR2(50 CHAR) NOT NULL,
    ACTIVATED_AT TIMESTAMP WITH TIME ZONE NOT NULL
);

-- BLOCK 3 CHILD TABLES
CREATE TABLE REG_SVC_PKG_VER (
    SERVICE_PACKAGE_VERSION_ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    VERSION_NUMBER NUMBER(10,0) NOT NULL,
    SERVICE_KNOWLEDGE CLOB NOT NULL,
    SERVICE_DEFINITION CLOB NOT NULL,
    INPUT_NAME VARCHAR2(100 CHAR) NOT NULL,
    FETCH_MODE VARCHAR2(10 CHAR) NOT NULL,
    DOCUMENT_SOURCE_QUERY_NAME VARCHAR2(100 CHAR),
    DOCUMENT_TYPE_COLUMN VARCHAR2(128 CHAR),
    DOCUMENT_PATH_COLUMN VARCHAR2(128 CHAR),
    DOCUMENT_CONTENT_COLUMN VARCHAR2(128 CHAR),
    APPROVAL_ENABLED NUMBER(1) DEFAULT 0 NOT NULL,
    APPROVAL_API VARCHAR2(500 CHAR),
    CONTENT_HASH VARCHAR2(64 CHAR) NOT NULL,
    LOADED_AT TIMESTAMP WITH TIME ZONE NOT NULL,
    SERVICE_PACKAGE_ID NUMBER(19) NOT NULL
);

CREATE TABLE REG_SVC_QUERY (
    SERVICE_QUERY_ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    QUERY_NAME VARCHAR2(100 CHAR) NOT NULL,
    CONNECTION_NAME VARCHAR2(100 CHAR) NOT NULL,
    SQL_TEXT CLOB NOT NULL,
    SERVICE_PACKAGE_VERSION_ID NUMBER(19) NOT NULL
);

CREATE TABLE REG_REQ_DOC (
    REQUIRED_DOCUMENT_ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    DOCUMENT_TYPE VARCHAR2(100 CHAR) NOT NULL,
    SERVICE_PACKAGE_VERSION_ID NUMBER(19) NOT NULL
);

-- REG_LOAD_RESULT has no FK; created after the registry tables
CREATE TABLE REG_LOAD_RESULT (
    LOAD_RESULT_ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    LOAD_RUN_AT TIMESTAMP WITH TIME ZONE NOT NULL,
    SUBJECT_KIND VARCHAR2(20 CHAR) NOT NULL,
    SUBJECT_NAME VARCHAR2(200 CHAR) NOT NULL,
    SERVICE_CODE VARCHAR2(100 CHAR),
    VERSION_NUMBER NUMBER(10,0),
    OUTCOME VARCHAR2(20 CHAR) NOT NULL,
    REASON VARCHAR2(1000 CHAR),
    CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);

