-- BLOCK 8 LOOKUP SEED DATA: none
--   Closed keys FETCH_MODE, CONNECTION_TYPE, LOAD_OUTCOME, LOAD_SUBJECT (SERVICE_PACKAGE, CONNECTION, PACKAGE_DIRECTORY) are enforced by the CHECK constraints of BLOCK 5c.
--   Load-run serialization (ADR-REG-015) needs no object: the run takes LOCK TABLE REG_LOAD_RESULT IN EXCLUSIVE MODE inside its one transaction.
--   Open keys SERVICE_CODE and DOCUMENT_TYPE are data: their values (scholarship-request; TRANSCRIPT, ID_CARD)
--   enter REG_SVC_PKG and REG_REQ_DOC when the delivered pilot package folder is loaded at start-up (ADR-REG-010).

